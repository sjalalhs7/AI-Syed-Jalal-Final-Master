import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
const root=process.cwd();
const html=fs.readFileSync(path.join(root,'frontend/index.html'),'utf8');
const runtime=fs.readFileSync(path.join(root,'backend/ai-runtime.mjs'),'utf8');
const server=fs.readFileSync(path.join(root,'backend/server.mjs'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'backend/package.json'),'utf8'));
const env=fs.readFileSync(path.join(root,'backend/.env.example'),'utf8');
assert.equal(pkg.version,'55.0.0');
assert.match(server,/const VERSION='V55'/);
assert.match(runtime,/Google Gemini \/ AI Studio/);
assert.match(runtime,/generativelanguage\.googleapis\.com\/v1beta/);
assert.match(runtime,/\/interactions/);
assert.match(runtime,/previous_interaction_id/);
assert.match(runtime,/google_search/);
assert.match(env,/GEMINI_API_KEY=/);
assert.match(html,/Google Gemini \/ AI Studio/);
assert.doesNotMatch(html,/localStorage\.setItem\('aj-v31-user'/);
assert.doesNotMatch(html,/localStorage\.setItem\('aj-v31-token'/);
assert.match(html,/prefers-reduced-motion/);
assert.match(html,/id="loginForm"/);
assert.match(html,/id="app"/);
assert.match(html,/id="paper"/);
const ids=[...html.matchAll(/\bid="([^"']+)"/g)].map(m=>m[1]);
const dup=ids.filter((x,i)=>ids.indexOf(x)!==i);
assert.equal(new Set(dup).size,0,`duplicate static IDs: ${[...new Set(dup)].join(',')}`);
console.log('V55 FINAL RELEASE: PASS');
console.log('Gemini: Google AI Studio / Interactions API + optional Google Search grounding');
console.log('UI: V55 homepage/login/app motion + reduced-motion preserved');
console.log('Security: server-side Gemini key configuration; no frontend API key storage');
